#!/usr/bin/env python3
"""Prepared hybrid certificate: one candidate, one 285s/30000-started-box run.

Importing this module does not evaluate any point or box. Actual execution
requires --run-approved, to be used only after the implementation review.
"""
from collections import deque
from fractions import Fraction as Q
from hashlib import sha256
import argparse
import importlib.util
import json
from pathlib import Path
import sys
from time import monotonic

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent
R = Q(15, 8)
E = {2: Q(69, 100), 6: Q(19, 50), 7: Q(11, 10), 8: Q(3, 4)}
DELTA, CAP_START = Q(1, 100), Q(99, 100)
SECONDS, BOX_LIMIT = 285., 30000
WIDTH_FLOOR = Q(1, 2**60)


class BudgetTime(Exception):
    pass


class Guard:
    def __init__(self):
        self.started = monotonic()
    def check(self):
        if monotonic()-self.started >= SECONDS:
            raise BudgetTime('285-second inclusive certification budget exhausted')


def import_source(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def row_box(box):
    return dict(zip(['r_lo', 'r_hi', 'q_lo', 'q_hi'], map(str, box)))


def cap_check(c, guard):
    """Recompute only the audited cap constants; target is real G, not G_N."""
    guard.check()
    proof = ROOT.parent/'round017/boundary_cap.md'
    verifier = ROOT.parent/'round017/verify_boundary_cap.py'
    saved_path = ROOT.parent/'round017/boundary_cap_verification.json'
    saved = json.loads(saved_path.read_text())
    assert saved['status'] == 'one_fixed_support_corner_cap_strictly_positive'
    assert saved['candidate_R'] == str(R) and saved['cap_r_q'] == [str(CAP_START), '1']
    assert saved['proof_sha256'] == sha256(proof.read_bytes()).hexdigest()
    assert saved['verifier_sha256'] == sha256(verifier.read_bytes()).hexdigest()
    eps, tau, bmax = Q(2, 199), Q(197, 199), Q(299, 20000)
    log2 = c.log_point(2)
    H = {2: 8-8*log2, 6: Q(1334, 5)-384*log2,
         7: Q(3108, 5)-896*log2, 8: Q(149104, 105)-2048*log2}
    omega, M = {2: 4*eps*(c.log_point(199).hi-1)}, {2: Q(4)}
    for p in [6, 7, 8]:
        guard.check()
        m, n = p-2, p-1
        K = 1/(tau*(p-1))+sum((eps**k/Q(m-k) for k in range(m)), Q(0))
        K += eps**m*c.log_point(1/eps).hi
        omega[p] = eps*max(Q(0), 2*p*(p-1)*K-4*p)
        M[p] = 2*p*(sum((Q(2**k+1, n-k) for k in range(n)), Q(0))+Q(1, 2*n))
    U = {p: H[p].hi+omega[p]+bmax**(p-1)*M[p] for p in E}
    F = sum((CAP_START**j/((j+2)*R**(j+1)) for j in range(29)), Q(0))
    tail = 2*(2*F+1/R)/(R-1)
    margin = tail-sum((E[p]*U[p] for p in E), Q(0))
    assert margin > 0 and margin == Q(saved['strict_cap_generator_margin_fraction'])
    guard.check()
    return {'target': 'real_G', 'domain': row_box((CAP_START, Q(1), CAP_START, Q(1))),
            'tail_lower': str(tail), 'bump_upper_by_power': {str(p): str(x) for p, x in U.items()},
            'generator_lower': str(margin), 'proof_dependency': 'round017/boundary_cap.md',
            'proof_sha256': saved['proof_sha256'], 'verifier_sha256': saved['verifier_sha256'],
            'saved_verification_sha256': sha256(saved_path.read_bytes()).hexdigest(),
            'core_sha256': saved['core_sha256']}


def prepare(guard):
    guard.check()
    base_path = ROOT.parent/'round017/compare_bounds.py'
    base = import_source('round018_centered_base', base_path)
    c, _, polys, tail_components, core_path, old_path = base.prepare()
    assert base.R == R and base.E == E
    guard.check()
    old = import_source('round018_candidate_auxiliary', old_path)
    assert old.R == R and old.E == E
    aux = old.auxiliary(c)
    guard.check()
    # Cv is constructed from the original r,q expression as an exact sparse
    # polynomial, never by a hand-entered derivative table.
    r = base.Poly({(1, 0): 1})
    q = base.Poly({(0, 1): 1})
    s, zm = 1-r, 1-r*q
    full_polys = {}
    for p, (P, Cu) in polys.items():
        guard.check()
        full_polys[p] = (P, Cu, zm**(p-1)+s**(p-1))
    cap = cap_check(c, guard)
    assert cap['core_sha256'] == sha256(core_path.read_bytes()).hexdigest()
    return base, c, polys, full_polys, tail_components, aux, cap, core_path, base_path, old_path


def complete_bundle(base, c, box, polys, tail_components, guard):
    rl, rh, ql, qh = box
    assert 1-rh > 0 and rl*(1-qh)/2 > 0 and 1-rh*qh > 0
    rc, qc = (rl+rh)/2, (ql+qh)/2
    AD = base.AD
    rp, qp = AD.variable(c.I.point(rc), 0), AD.variable(c.I.point(qc), 1)
    rb, qb = AD.variable(c.I(rl, rh), 0), AD.variable(c.I(ql, qh), 1)
    # All gradients/Hessians, including the corrected positive d_r v, are
    # generated by AD from original expressions. No table is injected.
    def variables(r, q):
        return r*(1+q)/2, r*(1-q)/2, 1-r, 1+r*q, 1-r*q
    up, vp, sp, zpp, zmp = variables(rp, qp)
    ub, vb, sb, zpb, zmb = variables(rb, qb)
    for x in [up, vp, sp, zpp, zmp, ub, vb, sb, zpb, zmb]:
        assert x.v.lo > 0
    point, uniform = base.tail_bundles(tail_components, box, guard)
    for p, (P, Cu, Cv) in polys.items():
        guard.check()
        Pp, Pb = base.shifted_bundles(P, box, guard)
        Cup, Cub = base.shifted_bundles(Cu, box, guard)
        Cvp, Cvb = base.shifted_bundles(Cv, box, guard)
        n, alpha = p-1, 2*p*E[p]
        point -= alpha*(Pp+Cup*up.log()+Cvp*vp.log()-zpp**n*zpp.log()
                        -zmp**n*zmp.log()-2*sp**n*sp.log())
        uniform -= alpha*(Pb+Cub*ub.log()+Cvb*vb.log()-zpb**n*zpb.log()
                          -zmb**n*zmb.log()-2*sb**n*sb.log())
    return point, uniform


def taylor_record(base, point, uniform, box):
    rr, rq = (box[1]-box[0])/2, (box[3]-box[2])/2
    mean = point.v.lo-base.maxabs(uniform.g[0])*rr-base.maxabs(uniform.g[1])*rq
    second = (point.v.lo-base.maxabs(point.g[0])*rr-base.maxabs(point.g[1])*rq
              -(base.maxabs(uniform.h[0][0])*rr*rr+2*base.maxabs(uniform.h[0][1])*rr*rq
                +base.maxabs(uniform.h[1][1])*rq*rq)/2)
    return max(mean, second), {'center_value': point.v.pair(),
                               'center_gradient': [x.pair() for x in point.g],
                               'uniform_gradient': [x.pair() for x in uniform.g],
                               'uniform_hessian': [[x.pair() for x in row] for row in uniform.h],
                               'mean_lower': str(mean), 'second_order_lower': str(second),
                               'best_lower': str(max(mean, second))}


def evaluate(base, c, box, polys, full_polys, tail_components, guard, counts):
    guard.check()
    rl, rh, ql, qh = box
    positive = {'s': 1-rh, 'v': rl*(1-qh)/2, 'zminus': 1-rh*qh}
    assert all(x >= 0 for x in positive.values())
    strict = all(x > 0 for x in positive.values())
    data = {'regularity_lower_endpoints': {name: str(x) for name, x in positive.items()},
            'center': [str((rl+rh)/2), str((ql+qh)/2)],
            'halfwidth': [str((rh-rl)/2), str((qh-ql)/2)]}
    full_lower = None
    if strict:
        counts['full_smooth_bundle_calls'] += 1
        counts['center_bundle_calls'] += 1
        counts['uniform_derivative_bundle_calls'] += 1
        point, uniform = complete_bundle(base, c, box, full_polys, tail_components, guard)
        guard.check()
        full_lower, full_data = taylor_record(base, point, uniform, box)
        data['full_smooth'] = full_data
        if full_lower >= 0:
            return full_lower, 'full_smooth', data
    # Boundary boxes never call a forbidden log first and recover from NaN.
    guard.check()
    if full_lower is not None:
        counts['split_fallback_calls'] += 1
    counts['split_bundle_calls'] += 1
    counts['center_bundle_calls'] += 1
    counts['uniform_derivative_bundle_calls'] += 1
    point, uniform = base.build_A(c, box, polys, tail_components, guard)
    guard.check()
    core_lower, split_data = taylor_record(base, point, uniform, box)
    singular, singular_data = base.singular_lower(c, box)
    guard.check()
    split_lower = core_lower+singular
    split_data.update({'singular_remainder': singular_data, 'total_lower': str(split_lower)})
    data['split_boundary'] = split_data
    if full_lower is not None and full_lower > split_lower:
        return full_lower, 'full_smooth_after_split_fallback', data
    return split_lower, 'split_boundary' if not strict else 'split_fallback', data


def initial_tree(cap):
    root = (DELTA, Q(1), Q(0), Q(1))
    d1 = (DELTA, CAP_START, Q(0), Q(1))
    dr = (CAP_START, Q(1), Q(0), Q(1))
    d2 = (CAP_START, Q(1), Q(0), CAP_START)
    k = (CAP_START, Q(1), CAP_START, Q(1))
    nodes = [
        {'id': 0, 'parent': None, **row_box(root), 'status': 'split', 'method': 'seed_partition',
         'axis': 'r', 'cutpoint': str(CAP_START), 'children': [1, 2]},
        {'id': 1, 'parent': 0, **row_box(d1), 'status': 'pending'},
        {'id': 2, 'parent': 0, **row_box(dr), 'status': 'split', 'method': 'seed_partition',
         'axis': 'q', 'cutpoint': str(CAP_START), 'children': [3, 4]},
        {'id': 3, 'parent': 2, **row_box(d2), 'status': 'pending'},
        {'id': 4, 'parent': 2, **row_box(k), 'status': 'accepted', 'method': 'analytic_cap'}]
    cap_leaf = {'node_id': 4, **row_box(k), 'method': 'analytic_cap',
                'generator_lower': cap['generator_lower'], 'cap_evidence': cap}
    return nodes, deque([(1, d1), (3, d2)]), [cap_leaf]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run-approved', action='store_true')
    args = parser.parse_args()
    if not args.run_approved:
        raise SystemExit('Prepared only. Use --run-approved after implementation review and explicit run authorization.')
    output = ROOT/'certificate.json'
    if output.exists():
        raise SystemExit('One attempt already has an output marker; no automatic retry or continuation.')
    guard = Guard()  # Inclusive clock starts before imports, construction, aux, cap.
    output.write_text(json.dumps({'round': 18, 'status': 'started', 'candidate_attempts': 1})+'\n')
    prepared_at = monotonic()
    try:
        base, c, polys, full_polys, tail_components, aux, cap, core_path, base_path, old_path = prepare(guard)
    except BudgetTime:
        root = (DELTA, Q(1), Q(0), Q(1))
        result = {'round': 18, 'status': 'not_closed', 'candidate_attempts': 1,
                  'stop_reason': 'time_budget_exhausted_during_preparation', 'complete_partition_cover': False,
                  'parameters': {'R': str(R), 'e_by_power': {str(p): str(e) for p, e in E.items()}},
                  'counts': {'boxes_started': 0, 'boxes_completed': 0, 'boxes_interrupted': 0},
                  'timing': {'inclusive_certification_seconds': monotonic()-guard.started},
                  'accepted_leaf_data': [],
                  'unresolved_queue': [{'node_id': 0, **row_box(root), 'reason': 'preparation_time_budget',
                                        'last_generator_lower': None}],
                  'partition_tree': [{'id': 0, 'parent': None, **row_box(root), 'status': 'pending'}],
                  'scope': 'No cap accepted and no numeric box started; no automatic retry.'}
        output.write_text(json.dumps(result, indent=2)+'\n')
        print(json.dumps(result, indent=2), flush=True)
        return
    preparation_seconds = monotonic()-prepared_at
    nodes, todo, leaves = initial_tree(cap)
    unresolved = []
    counts = {'boxes_started': 0, 'boxes_completed': 0, 'boxes_interrupted': 0,
              'full_smooth_bundle_calls': 0, 'split_bundle_calls': 0, 'split_fallback_calls': 0,
              'center_bundle_calls': 0, 'uniform_derivative_bundle_calls': 0,
              'analytic_cap_leaves': 1, 'cap_constant_checks': 1, 'seed_partition_splits': 2,
              'midpoint_splits': 0, 'numeric_accepted_leaves': 0, 'LPs': 0, 'extra_probe_boxes': 0}
    stop = 'queue_exhausted'
    numeric_minimum = None
    while todo:
        if counts['boxes_started'] >= BOX_LIMIT:
            stop = 'started_box_budget_exhausted'
            break
        try:
            guard.check()
        except BudgetTime:
            stop = 'time_budget_exhausted'
            break
        node_id, box = todo.popleft()
        counts['boxes_started'] += 1
        try:
            lower, method, evidence = evaluate(base, c, box, polys, full_polys, tail_components, guard, counts)
            counts['boxes_completed'] += 1
        except BudgetTime:
            counts['boxes_interrupted'] += 1
            nodes[node_id]['status'] = 'pending_interrupted_evaluation'
            unresolved.append({'node_id': node_id, **row_box(box), 'reason': 'time_interrupted_evaluation',
                               'last_generator_lower': None})
            stop = 'time_budget_exhausted'
            break
        if lower >= 0:
            nodes[node_id].update({'status': 'accepted', 'method': method})
            leaves.append({'node_id': node_id, **row_box(box), 'method': method,
                           'generator_lower': str(lower), 'evidence': evidence})
            counts['numeric_accepted_leaves'] += 1
            numeric_minimum = lower if numeric_minimum is None else min(numeric_minimum, lower)
        else:
            rl, rh, ql, qh = box
            if max(rh-rl, qh-ql) <= WIDTH_FLOOR:
                nodes[node_id]['status'] = 'unresolved_width_floor'
                unresolved.append({'node_id': node_id, **row_box(box), 'reason': 'width_floor',
                                   'last_generator_lower': str(lower), 'method': method, 'evidence': evidence})
            else:
                axis = 'r' if (rh-rl)/(1-DELTA) >= qh-ql else 'q'
                if axis == 'r':
                    cut = (rl+rh)/2
                    children = [(rl, cut, ql, qh), (cut, rh, ql, qh)]
                else:
                    cut = (ql+qh)/2
                    children = [(rl, rh, ql, cut), (rl, rh, cut, qh)]
                ids = []
                for child in children:
                    new_id = len(nodes)
                    ids.append(new_id)
                    nodes.append({'id': new_id, 'parent': node_id, **row_box(child), 'status': 'pending'})
                    todo.append((new_id, child))
                nodes[node_id].update({'status': 'split', 'method': 'exactmidpoint', 'axis': axis,
                                       'cutpoint': str(cut), 'children': ids})
                counts['midpoint_splits'] += 1
        if counts['boxes_completed'] % 100 == 0:
            print(json.dumps({'boxes_started': counts['boxes_started'], 'boxes_completed': counts['boxes_completed'],
                              'numeric_accepted_leaves': counts['numeric_accepted_leaves'], 'pending': len(todo),
                              'elapsed_seconds_inclusive': monotonic()-guard.started}), flush=True)
    elapsed = monotonic()-guard.started
    for node_id, box in todo:
        unresolved.append({'node_id': node_id, **row_box(box), 'reason': stop, 'last_generator_lower': None})
    cover = not unresolved and all(n['status'] in ['accepted', 'split'] for n in nodes)
    aux_passed = (aux['small_radius']['B_upper_negative'] and aux['small_radius']['B_upper_matches_audit']
                  and aux['exterior']['new_slack_positive'] and aux['kernel_dominance_positive']
                  and aux['strict_cost_improvement'])
    def area(row):
        return (Q(row['r_hi'])-Q(row['r_lo']))*(Q(row['q_hi'])-Q(row['q_lo']))
    accepted_area = sum((area(x) for x in leaves), Q(0))
    unresolved_area = sum((area(x) for x in unresolved), Q(0))
    root_area = 1-DELTA
    dependencies = {'round017/compare_bounds.py': base_path, 'round016/certify.py': old_path,
                    'round017/boundary_cap.md': ROOT.parent/'round017/boundary_cap.md',
                    'round017/boundary_cap_verification.json': ROOT.parent/'round017/boundary_cap_verification.json',
                    'round018/hybrid_bounds.md': ROOT/'hybrid_bounds.md', 'round018/PLAN.md': ROOT/'PLAN.md'}
    result = {'round': 18, 'status': 'closed_pending_independent_review' if cover and aux_passed else 'not_closed',
              'candidate_attempts': 1, 'parameters': {'R': str(R), 'e_by_power': {str(p): str(e) for p, e in E.items()}},
              'limits': {'seconds_including_preparation_aux_cap_and_boxes': SECONDS, 'boxes_started': BOX_LIMIT,
                         'width_floor': str(WIDTH_FLOOR), 'tail_r_n_max': 28, 'tail_even_k_max': 14},
              'timing': {'inclusive_certification_seconds': elapsed, 'preparation_aux_and_cap_seconds': preparation_seconds},
              'counts': counts, 'stop_reason': stop, 'complete_partition_cover': cover,
              'minimum_numeric_accepted_lower': str(numeric_minimum) if numeric_minimum is not None else None,
              'minimum_numeric_accepted_lower_display': float(numeric_minimum) if numeric_minimum is not None else None,
              'auxiliary': aux, 'analytic_cap': cap, 'accepted_leaf_data': leaves,
              'unresolved_queue': unresolved, 'partition_tree': nodes,
              'parameter_area_ledger_only': {'accepted_area': str(accepted_area), 'unresolved_area': str(unresolved_area),
                                           'root_area': str(root_area), 'accepted_fraction_of_root': str(accepted_area/root_area),
                                           'sum_equals_root': accepted_area+unresolved_area == root_area},
              'accepted_leaf_sha256': sha256(json.dumps(leaves, sort_keys=True, separators=(',', ':')).encode()).hexdigest(),
              'partition_tree_sha256': sha256(json.dumps(nodes, sort_keys=True, separators=(',', ':')).encode()).hexdigest(),
              'core_dependency': 'round008/certify.py', 'core_sha256': sha256(core_path.read_bytes()).hexdigest(),
              'certifier_sha256': sha256(Path(__file__).read_bytes()).hexdigest(),
              'dependencies': {name: sha256(path.read_bytes()).hexdigest() for name, path in dependencies.items()},
              'scope': 'One hybrid attempt, real-G cap and G_N interval leaves. Independent full replay and general transfer review required before any strict upper-bound update.'}
    output.write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({k: v for k, v in result.items() if k not in ['accepted_leaf_data', 'unresolved_queue', 'partition_tree']}, indent=2), flush=True)


if __name__ == '__main__':
    main()

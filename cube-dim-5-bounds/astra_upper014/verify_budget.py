"""One complete alpha=1 shape/flag budget and fixed alpha=3/2 control."""
from pathlib import Path
from fractions import Fraction as F
from math import floor
import hashlib,json,sys,time
import sympy as sp
from flint import arb,ctx

P=Path(__file__).resolve().parent

def ar(q):
    q=F(q)
    return arb(q.numerator)/q.denominator

def bracket(z,scale=10**15):
    # Float selects an integer only; both directed comparisons use Arb.
    k=floor(float(z)*scale)
    lo,hi=F(k-1,scale),F(k+2,scale)
    assert ar(lo)<z and z<ar(hi)
    return {'ball':str(z),'rational_lower':str(lo),'rational_upper':str(hi)}

def evaluate(alpha,types):
    beta=alpha/2;b=beta/5;q=F(5)/(5-alpha)
    rows=[];Z=arb(0)
    for t in types:
        R=arb(1)
        for hist in t['probability_histograms']:
            R*=sum((n*ar(p)**ar(beta) for p,n in hist.items()),arb(0))
        term=ar(t['theta'])*R**ar(1/beta);Z+=term
        rows.append({'R_beta':str(R),'weighted_Z_term':str(term)})
    moment=(ar(F(6,5))).gamma()/(1+ar(b)).gamma()
    J=arb(16)**ar(1-beta)*(1+ar(beta)).gamma()*moment**5*Z**(-ar(b))
    c=ar((5-alpha)/2).gamma()/(arb(2)**ar(alpha)*arb.pi()**ar(F(5,2))*16*ar(beta).gamma())
    I=c**ar(q)*arb.pi()**2/60*J**ar(q)
    critical=(5/ar(alpha))*(I/32)**ar(1/q)
    critical_normalized=critical/c
    for row in rows:
        row['optimized_type_weight']=str(arb(row['weighted_Z_term'])/Z)
    controls={}
    if alpha==1:
        assert c.overlaps(1/(32*arb.pi()**3))
        assert Z.contains(ar(F(2661,64)))
        controls['c_equals_1_over_32_pi_cubed']=True
        controls['Z_exact']='2661/64'
    else:
        assert c.overlaps(3/(arb(2)**ar(F(15,2))*arb.pi()**ar(F(5,2))))
        controls['c_equals_locked_alpha_3_2_constant']=True
    return {'alpha':str(alpha),'beta':str(beta),'b':str(b),'q':str(q),
            'types':rows,'Z':str(Z),'Gamma_ratio':str(moment),'J_upper_expression':bracket(J),
            'c':bracket(c),'I_upper_expression':bracket(I),
            'g_required_for_cost_32_using_exact_expression':bracket(critical),
            'g_over_c_required_for_cost_32':bracket(critical_normalized),
            'conditional_cost_at_same_unit_cube_g':{str(g):str((5/ar(alpha))**ar(q)*I/ar(g)**ar(q)) for g in (F(1,10000),F(16,125000),F(3,20000))},
            'normalization_controls':controls}

def main():
    began=time.monotonic();ctx.prec=384
    inp=json.loads((P/'flag_types.json').read_text());types=inp['types'];assert len(types)==5
    assert sum(t['count'] for t in types)==4560
    assert sum(t['sum_C'] for t in types)==60*16**5
    assert sum((F(t['theta']) for t in types),F(0))==1
    exact_R2=[]
    for t in types:
        assert F(t['theta'])==F(t['sum_C'],60*16**5)
        assert 2+sum(sum(h.values()) for h in t['probability_histograms'])==16
        R=sp.Integer(1)
        for h in t['probability_histograms']:
            assert sum((F(p)*n for p,n in h.items()),F(0))==1
            assert all(F(p)>0 and n>0 for p,n in h.items())
            R*=sum(n*sp.sqrt(sp.Rational(p)) for p,n in h.items())
        r2=sp.simplify(R**2);assert r2.is_Rational
        exact_R2.append(F(int(r2.p),int(r2.q)))
    assert exact_R2==[F(81,8),F(27),F(36),F(36),F(64)]
    Z=sum((F(t['theta'])*r for t,r in zip(types,exact_R2)),F(0));assert Z==F(2661,64)
    weights=[F(t['theta'])*r/Z for t,r in zip(types,exact_R2)]
    cases=[evaluate(F(1),types),evaluate(F(3,2),types)]
    out={'status':'complete_analytic_I_bounds_with_384bit_Arb_constant_certification',
         'new_C5_upper_bound':False,'new_global_g':False,
         'alpha1_exact_R_squared':[str(x) for x in exact_R2],
         'alpha1_exact_Z':str(Z),'alpha1_exact_optimized_weights':[str(x) for x in weights],
         'cases':cases,
         'checks':{'probabilities_and_mass_exact':True,'scope_each_flag_16':True,'alpha1_R_squared_recomputed_from_probabilities':True},
         'limitations':['The supplied locked 022 geometric flag identity is an input; it is not regenerated by this batch.',
                        'I_upper_expression denotes a proven upper bound, not the actual I.',
                        'Conditional cost and required g do not supply a g certificate.'],
         'source_hashes':{s.name:hashlib.sha256(s.read_bytes()).hexdigest() for s in [P/'registration.md',P/'flag_types.json',Path(__file__)]},
         'runtime':{'python':sys.executable,'sympy':sp.__version__,'arb_bits':ctx.prec,'seconds':time.monotonic()-began}}
    (P/'budget.json').write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps({'exact_R_squared':out['alpha1_exact_R_squared'],'exact_Z':str(Z),'weights':out['alpha1_exact_optimized_weights'],'cases':[{k:v for k,v in c.items() if k not in ('types',)} for c in cases],'runtime':out['runtime']},indent=2))

if __name__=='__main__':main()

"""Actual full satellite unions, explicitly including N0=0 singleton images."""
from pathlib import Path
from itertools import product
import time,json
import numpy as np
from scipy.optimize import minimize
from round004_satellite_search import A,PRIMARY,capture,evaluate
from round005_exposure import geometry
from round005_calibrate import face_keys
P=Path(__file__).resolve().parent;OLD=1.9017426111009554
PURE=set()
for k in product([-1,0,1],repeat=4):PURE.add(tuple([0]*4+list(k)+[-1]*4+list(k)))

def actual(a,phi,eps,pool,power=8,seed=20261025606):
    row,keys=evaluate(a,phi,eps,power=power,seed=seed,pool=set(pool)|PURE)
    row['explicit_pure_singletons']=81;row['increment_quotient']=(row['ratio']-OLD)/eps
    return row,keys

def save_candidate(row,keys):
    extra=sorted(set(keys)-set(PRIMARY));(P/'round006_actual_candidate.json').write_text(json.dumps(dict(row=row,additional_keys=[list(k) for k in extra],primary_keys='generated by PRIMARY in round004_satellite_search.py',status='numerical candidate; requires exact certificate'),separators=(',',':'))+'\n')

def main():
    start=time.monotonic();data=json.loads((P/'round006_screen_results.json').read_text());patches,_,_=geometry();rows=[];runs=[];bestcandidate=None
    starts=[data['candidate']] if data['candidate'] else sorted(data['runs'],key=lambda r:-r['prediction'])[:2]
    pools=[]
    for st in starts:
        phi=np.array(st['phi']);d=np.array(st['direction']);pool,meta=face_keys(phi,patches);pools.append(pool);print('START',st,meta,flush=True)
        for eps in [.003,.001,.0003,.0001]:
            row,keys=actual(A*(1+eps*d),phi,eps,pool,power=10);rows.append(row);print('CAL',row,flush=True)
            if row['ratio']>OLD+1e-7:
                rr,kk=actual(np.array(row['a']),phi,eps,keys,power=12,seed=20261025607);rows.append(rr);save_candidate(rr,kk);bestcandidate=rr;break
        if bestcandidate:break
    stop='finite calibrations complete'
    if bestcandidate is None:
        # Joint period/phase/mass objective: a positive quotient is equivalent to a new finite ratio.
        for index,(st,pool) in enumerate(zip(starts,pools)):
            initial=max((r for r in rows if np.max(abs(np.array(r['phi'])-st['phi']))<1e-10),key=lambda r:r['increment_quotient'])
            if OLD-initial['ratio']>=.002:continue
            x=np.r_[initial['a'],initial['phi'],initial['epsilon']]
            def obj(y):
                nonlocal bestcandidate
                r,k=actual(y[:4],y[4:8],y[8],pool,power=8);rows.append(r)
                if len(rows)%25==0:print('OPT',len(rows),r,flush=True)
                if r['ratio']>OLD+1e-7:save_candidate(r,k);bestcandidate=r;raise RuntimeError('positive finite candidate; exact certificate priority')
                return -r['increment_quotient']
            try:
                res=minimize(obj,x,method='Nelder-Mead',bounds=[(.97*a,1.04*a) for a in A]+[(0,.5)]*4+[(1e-5,.02)],options={'maxfev':300,'xatol':1e-8,'fatol':1e-8})
                runs.append(dict(index=index,nfev=res.nfev,quotient=float(-res.fun),x=res.x.tolist(),stop=str(res.message)));print('RUN',runs[-1],flush=True)
            except RuntimeError as e:stop=str(e);break
    result=dict(status='actual finite witness joint union only; no input/family upper bound',stop=stop,rows=rows,runs=runs,candidate=bestcandidate,elapsed=time.monotonic()-start,explicit_singleton_keys=81)
    (P/'round006_actual_results.json').write_text(json.dumps(result,indent=2)+'\n');print('FINAL',stop,'best',max(r['ratio'] for r in rows),'best quotient',max(r['increment_quotient'] for r in rows),flush=True)
if __name__=='__main__':main()
